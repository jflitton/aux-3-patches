#!/usr/bin/env python3
"""Generate the Sonora kernel patch (LC III, LC III+) for an A/UX kernel (/unix or
/etc/config.d/newunix).

  kernel-patch.py KERNEL ld                 kernel-specific link symbols (boardinit_switch)
  kernel-patch.py KERNEL spec ELF BIN       tools/binpatch.py spec, for /unix and newunix

The patch is the code linked by patches/sonora/build.sh (src/sonora.S) placed over
orwellsize and memcdjsize in pstart, plus redirected call sites:

  orwellsize                          the code itself
  _start: jsr boardinit               jsr sonora_board
  boardinit: move.w machineID,d0;     jmp sonora_switch; 3 nops
    ext.l d0; bra.w <switch>
  memsize: tst.l rbv_exists           jsr sonora_rbv (the bne.w after it stays)
  memsize (one bank):                 clr.l -(sp); jsr sonora_banksize
    moveq #0,d0; move.l d0,-(sp);
    jsr banksize
  vadrspace: jsr setup_autovectors    jsr sonora_vectors
  aEgretDispatch: jsr cEgretDispatch  jsr sonora_egret
  cEgretDispatch: link.l a6,#-12      jmp sonora_cegret (which does the link and jumps back)

A checkpoint build (CKPT=1, src/sonora.S) also redirects, in /unix only (autoconfig
writes these tables), init_first's egret_init, video_init and fdb_init entries, main's jsr
startup, and initfunc's iinit and nvram_init entries to the ck_* trampolines.

pstart is identity-mapped, so every hook is entered at its link address, MMU on or off.
Sites are found by symbol and instruction pattern (tools/kpatch.py). autoconfig rewrites
only configuration data, so /unix and the newunix it is linked from take the same patch.
"""
import os, struct, sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'tools'))
from kpatch import CLR_SP, JMP, JSR, NOP, Kernel, elf_symbols, emit  # noqa: E402

LINK_A6_12 = b'\x48\x0e\xff\xff\xff\xf4'


def main():
    k, cmd = Kernel(sys.argv[1]), sys.argv[2]
    if cmd == 'ld':
        print('boardinit_switch = 0x%08x;' % k.boardinit_switch()[1])
        return
    esym, blob = elf_symbols(sys.argv[3]), open(sys.argv[4], 'rb').read()
    if esym['issonora'] != k.sym['orwellsize']:
        raise SystemExit('the code is not linked at orwellsize')
    if k.section(k.sym['orwellsize'])['name'] != 'pstart':
        raise SystemExit('orwellsize is not in pstart')
    ptr = lambda name: struct.pack('>I', esym[name])
    switch_site, _ = k.boardinit_switch()
    rbv_site, banksize_site = k.memsize_rbv()
    egret = k.sym['aEgretDispatch'] + 2
    if k.read(egret, 6) != JSR + struct.pack('>I', k.sym['cEgretDispatch']):
        raise SystemExit('aEgretDispatch+2 is not jsr cEgretDispatch')
    if k.read(k.sym['cEgretDispatch'], 6) != LINK_A6_12:
        raise SystemExit('cEgretDispatch does not start with link.l a6,#-12')
    sites = [
        (k.sym['orwellsize'], blob, 'LC III hooks (%d bytes)' % len(blob)),
        (k.find_call('pstart', 'boardinit'), JSR + ptr('sonora_board'),
         'jsr sonora_board, was boardinit'),
        (switch_site, JMP + ptr('sonora_switch') + NOP * 3, 'jmp sonora_switch'),
        (rbv_site, JSR + ptr('sonora_rbv'), 'jsr sonora_rbv, was tst.l rbv_exists'),
        (banksize_site, CLR_SP + JSR + ptr('sonora_banksize'),
         'clr.l -(sp); jsr sonora_banksize, was banksize'),
        (k.find_call('pstart', 'setup_autovectors'), JSR + ptr('sonora_vectors'),
         'jsr sonora_vectors, was setup_autovectors'),
        (egret, JSR + ptr('sonora_egret'), 'jsr sonora_egret, was cEgretDispatch'),
        (k.sym['cEgretDispatch'], JMP + ptr('sonora_cegret'),
         'jmp sonora_cegret, was link.l a6,#-12'),
    ]
    print('; Sonora kernel patch (LC III, LC III+), generated by')
    print('; patches/sonora/kernel-patch.py from %s' % os.path.basename(sys.argv[1]))
    print('; Apply with tools/binpatch.py; /unix and the newunix autoconfig links it from.')
    print('file /unix /etc/config.d/newunix')
    emit(k, sites)
    if 'ck_startup' in esym:
        print()
        print('; checkpoint build: hold a checkpoint key through "Launching" to restart there')
        print('file /unix')
        emit(k, [(k.table_entry('init_first', f), ptr('ck_' + f), 'init_first: ck_' + f)
                 for f in ('egret_init', 'video_init', 'fdb_init')] + [
            (k.find_call('.text', 'startup'), JSR + ptr('ck_startup'),
             'main: jsr ck_startup, was startup')] + [
            (k.table_entry('initfunc', f), ptr('ck_' + f), 'initfunc: ck_' + f)
            for f in ('iinit', 'nvram_init')])


if __name__ == '__main__':
    main()
